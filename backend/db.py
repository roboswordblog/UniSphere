def get_connection():
    if USE_POSTGRES:
        if psycopg is None:
            raise RuntimeError("Install psycopg to use PostgreSQL: pip install -r backend/requirements.txt")

        connection = psycopg.connect(DATABASE_URL, row_factory=dict_row)
        return PostgresConnection(connection)

    connection = sqlite3.connect(DATABASE_PATH)
    connection.row_factory = sqlite3.Row
    return connection


class PostgresConnection:
    def __init__(self, connection):
        self.connection = connection

    def __enter__(self):
        self.connection.__enter__()
        return self

    def __exit__(self, exc_type, exc_value, traceback):
        return self.connection.__exit__(exc_type, exc_value, traceback)

    def execute(self, sql, params=None):
        cursor = self.connection.cursor()
        cursor.execute(convert_sqlite_to_postgres(sql), params or ())
        return cursor

    def executemany(self, sql, params):
        cursor = self.connection.cursor()
        cursor.executemany(convert_sqlite_to_postgres(sql), params)
        return cursor

    def executescript(self, script):
        for statement in convert_schema_to_postgres(script):
            self.execute(statement)


def convert_sqlite_to_postgres(sql):
    converted = sql.replace("?", "%s")

    if "INSERT OR IGNORE INTO" in converted:
        converted = converted.replace("INSERT OR IGNORE INTO", "INSERT INTO")
        converted = f"{converted.rstrip().rstrip(';')} ON CONFLICT DO NOTHING"

    return converted


def convert_schema_to_postgres(script):
    converted = script.replace(
        "INTEGER PRIMARY KEY AUTOINCREMENT",
        "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
    )
    converted = converted.replace("INSERT OR IGNORE INTO", "INSERT INTO")
    statements = []

    for raw_statement in converted.split(";"):
        statement = raw_statement.strip()

        if not statement:
            continue

        if statement.startswith("INSERT INTO colleges") or statement.startswith("INSERT INTO events"):
            statement = f"{statement} ON CONFLICT DO NOTHING"

        statements.append(statement)

    return statements


def initialize_database():
    with get_connection() as connection:
        connection.executescript(SCHEMA_PATH.read_text())
        ensure_user_columns(connection)


def ensure_database():
    initialize_database()


def load_sync_config():
    if not CONFIG_PATH.exists():
        return DEFAULT_SYNC_CONFIG.copy()

    with CONFIG_PATH.open("rb") as config_file:
        config = tomllib.load(config_file)

    sync_config = DEFAULT_SYNC_CONFIG.copy()
    sync_config.update(config.get("events_sync", {}))
    return sync_config


def ensure_user_columns(connection):
    if USE_POSTGRES:
        columns = {
            row["column_name"]
            for row in connection.execute(
                """
                SELECT column_name
                FROM information_schema.columns
                WHERE table_name = 'users'
                """
            ).fetchall()
        }
    else:
        columns = {
            row["name"]
            for row in connection.execute("PRAGMA table_info(users)").fetchall()
        }

    if "college_id" not in columns:
        connection.execute("ALTER TABLE users ADD COLUMN college_id INTEGER")

    if "profile_image" not in columns:
        connection.execute("ALTER TABLE users ADD COLUMN profile_image TEXT DEFAULT ''")


def fetch_json(url):
    request = Request(url, headers={"User-Agent": "UniSphere/0.1"})
    context = ssl.create_default_context(cafile=certifi.where())

    try:
        with urlopen(request, timeout=12, context=context) as response:
            return json.loads(response.read().decode("utf-8"))
    except (HTTPError, URLError, TimeoutError, json.JSONDecodeError) as error:
        raise RuntimeError(f"Could not fetch event source: {url}") from error


